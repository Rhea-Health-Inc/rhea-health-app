import { createFileRoute, Link } from "@tanstack/react-router";
import { PageHeader, SectionHeader } from "@/components/clinik/PageHeader";
import { StatCard, Panel, Badge, Table, Td, Tr, statusTone } from "@/components/clinik/AdminUI";
import { RequirePermission } from "./admin";
import {
  ATTENTION_ITEMS,
  DEPARTMENTS,
  INTEGRATIONS,
  LICENSE_SUMMARY,
  ORG_USERS,
  RECENT_ACTIVITY,
} from "@/lib/admin";

export const Route = createFileRoute("/admin/")({
  head: () => ({
    meta: [
      { title: "Administration overview - Rhea" },
      {
        name: "description",
        content: "Organization-level operational overview for your Rhea enterprise workspace.",
      },
      { name: "robots", content: "noindex" },
    ],
  }),
  component: () => (
    <RequirePermission permission="admin.access" label="the administration overview">
      <OverviewPage />
    </RequirePermission>
  ),
});

function OverviewPage() {
  const active = ORG_USERS.filter((u) => u.status === "Active").length + 268;
  const invited = ORG_USERS.filter((u) => u.status === "Invited").length;
  const deactivated = ORG_USERS.filter((u) => u.status === "Deactivated").length + 9;
  const degraded = INTEGRATIONS.filter((i) => i.status !== "Connected").length;

  return (
    <div className="px-12 py-14 max-w-6xl">
      <PageHeader
        breadcrumb={[{ label: "Administration", to: "/admin" }, { label: "Overview" }]}
        title="Overview"
        description="A single operational view of your organization: people, licenses, usage, and the systems Rhea depends on."
      />

      <section className="mb-14">
        <SectionHeader
          title="Users"
          description="Membership across every department in the organization."
        />
        <div className="grid gap-5 sm:grid-cols-3">
          <StatCard
            label="Active users"
            value={active}
            hint="Signed in within the last 30 days."
            tone="positive"
          />
          <StatCard
            label="Pending invitations"
            value={invited}
            hint="Invitations sent but not yet accepted."
            tone="warning"
          />
          <StatCard
            label="Deactivated users"
            value={deactivated}
            hint="Access revoked, records retained."
          />
        </div>
      </section>

      <section className="mb-14">
        <SectionHeader
          title="Licenses"
          description="Enterprise license pool allocated under your contract."
        />
        <div className="grid gap-5 sm:grid-cols-3">
          <StatCard
            label="Purchased licenses"
            value={LICENSE_SUMMARY.purchased}
            hint="Contracted for the current term."
          />
          <StatCard
            label="Assigned licenses"
            value={LICENSE_SUMMARY.assigned}
            hint="Currently attached to a user."
            tone="positive"
          />
          <StatCard
            label="Available licenses"
            value={LICENSE_SUMMARY.available}
            hint="Ready to assign without a purchase."
          />
        </div>
      </section>

      <section className="mb-14">
        <SectionHeader
          title="Usage"
          description="Volume generated by clinicians this billing period."
        />
        <div className="grid gap-5 sm:grid-cols-3">
          <StatCard label="Documentation" value="6,420 notes" hint="Generated month to date." />
          <StatCard label="Recording" value="968 hours" hint="Ambient capture month to date." />
          <StatCard label="Storage" value="1.42 TB" hint="Recordings and documents retained." />
        </div>
      </section>

      <section className="mb-14">
        <SectionHeader
          title="Departments and system status"
          description="Structure and platform health at a glance."
        />
        <div className="grid gap-5 sm:grid-cols-2 lg:grid-cols-4">
          <StatCard
            label="Total departments"
            value={DEPARTMENTS.length}
            hint="Configured in the organization."
          />
          <StatCard
            label="Active departments"
            value={DEPARTMENTS.filter((d) => d.active).length}
            hint="Accepting documentation."
          />
          <StatCard
            label="Integration status"
            value={degraded === 0 ? "Healthy" : `${degraded} need attention`}
            hint="Across EHR, calendar, identity, and data connectors."
            tone={degraded ? "warning" : "positive"}
          />
          <StatCard
            label="Security status"
            value="2 policy gaps"
            hint="MFA enforcement and IP allow-list review."
            tone="warning"
          />
        </div>
      </section>

      <section className="mb-14">
        <SectionHeader
          title="Attention required"
          description="Items an administrator should resolve."
        />
        <Panel padded={false}>
          <div className="divide-y divide-border/60">
            {ATTENTION_ITEMS.map((a) => (
              <Link
                key={a.id}
                to={a.to}
                className="flex items-start gap-4 px-8 py-5 hover:bg-muted/60 transition"
              >
                <span className="mt-1.5">
                  <Badge
                    tone={
                      a.severity === "high"
                        ? "danger"
                        : a.severity === "medium"
                          ? "warning"
                          : "neutral"
                    }
                  >
                    {a.severity === "high" ? "High" : a.severity === "medium" ? "Medium" : "Low"}
                  </Badge>
                </span>
                <span className="min-w-0">
                  <span className="block text-[15px] font-medium">{a.title}</span>
                  <span className="block mt-1 text-[14px] text-muted-foreground leading-relaxed">
                    {a.detail}
                  </span>
                </span>
              </Link>
            ))}
          </div>
        </Panel>
      </section>

      <section className="mb-6">
        <SectionHeader
          title="Recent administrative activity"
          description="The latest organization-level changes."
        />
        <Panel padded={false}>
          <Table head={["Time", "User", "Action", "Resource", "Department", "Result"]}>
            {RECENT_ACTIVITY.map((e) => (
              <Tr key={e.id}>
                <Td className="text-muted-foreground whitespace-nowrap">{e.at}</Td>
                <Td>{e.actor}</Td>
                <Td>{e.action}</Td>
                <Td className="text-muted-foreground">{e.resource}</Td>
                <Td className="text-muted-foreground">{e.department}</Td>
                <Td>
                  <Badge tone={statusTone(e.result)}>{e.result}</Badge>
                </Td>
              </Tr>
            ))}
          </Table>
          <div className="px-8 py-5 border-t border-border">
            <Link to="/admin/audit" className="text-[14px] text-primary hover:underline">
              View full audit log
            </Link>
          </div>
        </Panel>
      </section>
    </div>
  );
}
